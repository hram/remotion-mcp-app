import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { RenderInternals } from "@remotion/renderer";

const directory = path.resolve(process.argv[2]);
const file = path.join(directory, "android-ui-renderer-x.mp4");
const executable = (type: "ffmpeg" | "ffprobe") => RenderInternals.getExecutablePath({ type, logLevel: "error", indent: false, binariesDirectory: null });
const probe = JSON.parse(execFileSync(executable("ffprobe"), ["-v", "error", "-show_streams", "-show_format", "-of", "json", file], { encoding: "utf8" }));
const video = probe.streams.find((stream: { codec_type: string }) => stream.codec_type === "video");
assert.equal(video.codec_name, "h264");
assert.equal(video.pix_fmt, "yuv420p");
assert.equal(video.width, 1920);
assert.equal(video.height, 1080);
assert.equal(video.r_frame_rate, "30/1");
assert.equal(Number(video.nb_frames), 210);
assert.equal(Number(video.duration), 7);
assert.ok(probe.streams.every((stream: { codec_type: string }) => stream.codec_type !== "audio"));
const bytes = (await stat(file)).size;
assert.ok(bytes < 512 * 1024 * 1024);
execFileSync(executable("ffmpeg"), ["-v", "error", "-i", file, "-c:v", "rawvideo", "-f", "null", "-"], { stdio: "pipe" });
const log = JSON.parse(await readFile(path.join(directory, "pipeline-log.json"), "utf8"));
assert.equal(log.exports, 1);
assert.equal(log.calls.filter((call: { tool: string }) => call.tool === "export_video").length, 1);
assert.equal(log.calls.filter((call: { tool: string }) => call.tool === "inspect_frames").length, 3);
const report = { width: video.width, height: video.height, fps: 30, frames: 210, durationSeconds: 7, codec: video.codec_name, pixelFormat: video.pix_fmt, audioStreams: 0, bytes, decodedSuccessfully: true, visualIterationsAfterInitial: 2, inspections: 3, previewWidth: 480, previewHeight: 270, previewFramesPerInspection: 7, exportCalls: 1 };
await writeFile(path.join(directory, "verification.json"), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
